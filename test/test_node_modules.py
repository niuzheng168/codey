"""Run copied module bundles in isolation; no accounts, services or network changes."""
from contextlib import ExitStack
import importlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
from types import SimpleNamespace
import unittest
from unittest.mock import Mock, patch

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "skills/config-new-codey-machine/scripts"
sys.path.insert(0, str(SCRIPTS))
from codey_node.common.files import protected_write
from codey_node.service import bundle, launcher


class ModuleTests(unittest.TestCase):
    def test_each_runtime_is_self_contained_and_importable_without_the_skill_or_cwd(self):
        for platform in ("linux", "windows", "macos"):
            if platform == "macos" and os.name == "nt":
                continue  # Its real fcntl import is exercised on A100, not emulated.
            with self.subTest(platform=platform), tempfile.TemporaryDirectory() as temporary:
                root = Path(temporary)
                runtime = bundle.install_bundle(SCRIPTS, root / "service", platform)
                result = subprocess.run(
                    [sys.executable, "-I", "-B", "-c",
                     "import importlib,sys;sys.path.insert(0,sys.argv[1]);"
                     "m=importlib.import_module('codey_node.platforms.'+sys.argv[2]+'.supervisor');"
                     "assert callable(m.serve);print('MODULE_IMPORT_OK')", str(root / "service"), platform],
                    cwd=root, text=True, capture_output=True, timeout=20)
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertEqual(result.stdout.strip(), "MODULE_IMPORT_OK")
                self.assertNotIn("install.py", str(runtime["fileHashes"]))
                self.assertFalse(list(root.rglob("__pycache__")))
                before = {p: p.read_bytes() for p in (root / "service").rglob("*") if p.is_file()}
                self.assertEqual(bundle.install_bundle(SCRIPTS, root / "service", platform), runtime)
                self.assertEqual(before, {p: p.read_bytes() for p in before})

    def test_complete_bundle_is_checked_before_the_native_supervisor_is_dispatched(self):
        platform = {"win32": "windows", "linux": "linux", "darwin": "macos"}[sys.platform]
        for damage in (None, "modified", "missing", "extra", "missing-manifest-entry"):
            with self.subTest(damage=damage), tempfile.TemporaryDirectory() as temporary:
                root = Path(temporary)
                runtime = bundle.install_bundle(SCRIPTS, root / "service", platform)
                helper = root / "service/codey_node/devtunnel/auth.py"
                if damage == "modified":
                    helper.write_bytes(helper.read_bytes() + b"\nraise RuntimeError('must-not-import')\n")
                elif damage == "missing":
                    helper.unlink()
                elif damage == "extra":
                    (helper.parent / "unreviewed.py").write_text("raise RuntimeError('must-not-import')")
                elif damage == "missing-manifest-entry":
                    del runtime["fileHashes"]["codey_node/devtunnel/auth.py"]
                config = root / "runtime.json"
                protected_write(config, json.dumps({"pythonRuntime": runtime}))
                serve = Mock()
                with patch.object(launcher, "__file__", runtime["entrypoint"]), \
                     patch.object(launcher.sys, "path", list(sys.path)), \
                     patch.object(launcher.importlib, "import_module",
                                  return_value=SimpleNamespace(serve=serve)) as imported:
                    if damage:
                        with self.assertRaises(RuntimeError):
                            launcher.main(["--config", str(config), "--component", "renew"])
                        imported.assert_not_called()
                        serve.assert_not_called()
                    else:
                        launcher.main(["--config", str(config), "--component", "renew"])
                        imported.assert_called_once_with(f"codey_node.platforms.{platform}.supervisor")
                        serve.assert_called_once_with(config, "renew")

    def test_new_entry_ignores_an_untrusted_cwd_and_pythonpath(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            malicious = root / "codey_node"
            malicious.mkdir()
            (malicious / "__init__.py").write_text("raise RuntimeError('wrong package')")
            for platform in ("linux", "windows"):
                result = subprocess.run([sys.executable, "-I", "-B", SCRIPTS / "codey.py", platform, "--help"],
                                        cwd=root, env={**os.environ, "PYTHONPATH": str(root)},
                                        capture_output=True, text=True, timeout=20)
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertIn("--apply", result.stdout)
                self.assertNotIn("--resume", result.stdout)
                self.assertFalse((root / "assets").exists())

    def test_binary_copy_preserves_crlf_and_utf8_bytes_for_sha_pinning(self):
        with tempfile.TemporaryDirectory() as temporary:
            file = Path(temporary) / "example.py"
            data = '# 中文\r\nvalue = "test"\r\n'.encode()
            protected_write(file, data)
            self.assertEqual(file.read_bytes(), data)


if __name__ == "__main__":
    unittest.main()
